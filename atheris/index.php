            <div class="content-group">
                <p>
                    Long-duration spaceflight places the human body in an environment very different from Earth. In microgravity,
                    bones receive less mechanical loading, which can shift the balance between bone formation and bone resorption.
                    Spaceflight can also be associated with changes in vision and structures around the eye and brain.
                </p>
                <p>
                    Atheris Care is a proposed astronaut health-monitoring concept. It brings mission information and health
                    observations together so that measurements can be reviewed over time, compared with an astronaut's own
                    baseline when the methods are compatible, and shared with the medical team for review.
                </p>
            </div>
            
            <div class="content-group second-group">
                <p>
                    Our team's research focuses on two important spaceflight health concerns: bone loss in microgravity and
                    Spaceflight-Associated Neuro-ocular Syndrome (SANS). The research reviews how reduced mechanical loading
                    can affect bone, and how some astronauts experience changes involving vision, the retina and the optic nerve.
                </p>
                <p class="mb-0">
                    Atheris Care is designed to keep each result with its date, unit, method and quality notes. It can help organise
                    comparable measurements across pre-flight, in-flight and post-flight stages. The system supports medical review;
                    it does not diagnose a condition or replace a qualified health professional.
                </p>
            </div>
        </div>
    </div>
